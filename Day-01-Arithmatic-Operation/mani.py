a = 20
b = 6

# Addition
print("Addition:", a + b)

# Subtraction
print("Subtraction:", a - b)

# Multiplication
print("Multiplication:", a * b)

# Division
print("Division:", a / b)

# Modulus (remainder)
print("Modulus:", a % b)

# Exponentiation (power)
print("Exponentiation:", a ** b)

# Floor Division
print("Floor Division:", a // b)
 
